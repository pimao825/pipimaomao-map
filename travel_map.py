DATA_FILE = "travel_data.json"

# 加载本地保存的记录
def load_data():
    if os.path.exists(DATA_FILE):
        with open(DATA_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return {"visited_provinces": [], "visited_spots": []}

